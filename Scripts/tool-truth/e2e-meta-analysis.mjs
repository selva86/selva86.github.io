// ---------- 4. 2x2 arithmetic is shown ----------
{
  const c = C('counts_basic');
  await setStudies('counts', rowsOf(c), 95);
  const t = await inner('pertbl');
  ok('2x2 shows ln(ad/bc) arithmetic', /ln\(12.*80.*88.*20\)/.test(t.replace(/\s+/g, '')), t.split('\n')[1]);
  ok('2x2 shows SE arithmetic', /sqrt\(1\/12\+1\/88\+1\/20\+1\/80\)/.test(t.replace(/\s+/g, '')));
  const how = await raw('howsteps');
  ok('how-computed shows log OR step', /yi = ln/.test(how), how.slice(0, 90));
  ok('how-computed shows the DL tau2 arithmetic', /max\(0, \(Q . df\) \/ C\)/.test(how), how.slice(-160));
  ok('how-computed shows the FE weight formula', /w = 1 \/ SE/.test(how));
  const r = await txt('rcodepre');
  ok('R code emits escalc for counts', /escalc\(measure = "OR"/.test(r), r.slice(0, 60));
  ok('R code emits rma FE', /method = "FE"/.test(r));
  ok('R code emits rma DL', /method = "DL"/.test(r));
  ok('R code emits forest', /forest\(re/.test(r));
}
// zero-cell correction is visible
