/* E2E for tools/meta-analysis-quick-tool.html
   Asserts the RENDERED numbers against Scripts/tool-truth/meta-analysis-quick-tool.json,
   which is itself generated by R metafor (rma method="FE"/"DL", escalc measure="OR").
   Run: node Scripts/tool-truth/e2e-meta-analysis.mjs http://127.0.0.1:8237
*/
import { chromium } from 'playwright';
import { readFileSync } from 'fs';

const BASE = process.argv[2] || 'http://127.0.0.1:8237';
const PAGE_URL = `${BASE}/tools/meta-analysis-quick-tool.html?fresh=${Date.now()}`;
const TRUTH = JSON.parse(readFileSync(new URL('./meta-analysis-quick-tool.json', import.meta.url)));
const cases = Array.isArray(TRUTH.cases) ? TRUTH.cases : Object.values(TRUTH.cases || TRUTH);
const C = n => cases.find(c => c.name === n);

let pass = 0, fail = 0;
const errs = [];
function ok(name, cond, got) { if (cond) pass++; else { fail++; console.log(`FAIL ${name}` + (got !== undefined ? ` (got ${JSON.stringify(got)})` : '')); } }
function near(name, got, want, dp = 2) {
  const g = Number(got), w = Number(want);
  const okk = Math.abs(g - w) < 0.5 * Math.pow(10, -dp) + 1e-9;
  if (okk) pass++; else { fail++; console.log(`FAIL ${name}: got ${got}, want ${w.toFixed(dp)}`); }
}

const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await ctx.newPage();
page.on('pageerror', e => errs.push('pageerror: ' + String(e).slice(0, 200)));
page.on('console', m => {
  if (m.type() !== 'error') return;
  const t = m.text();
  if (/cloudflareinsights|beacon|ERR_|net::/i.test(t)) return; // CF beacon CORS on localhost
  // Resource-load failures are asserted with URLs by the response handler below,
  // where they can be judged individually; the bare console echo carries no URL.
  if (/Failed to load resource/i.test(t)) return;
  errs.push('console: ' + t.slice(0, 200));
});
// Site-wide chrome scripts call endpoints that only exist behind Cloudflare:
// consent-banner.js -> /cdn-cgi/trace (geo), auth-hydrate.js -> /api/me (session).
// Both 404 against a bare python http.server and are not this tool's doing.
const INFRA_404 = /\/cdn-cgi\/trace|\/api\/me/;
page.on('response', r => {
  if (r.status() >= 400 && !INFRA_404.test(r.url())) errs.push(`http ${r.status()}: ${r.url().slice(0, 120)}`);
});

const txt = id => page.$eval('#' + id, e => e.textContent.trim());
const inner = id => page.$eval('#' + id, e => e.innerText.trim());
// #howsteps lives inside a collapsed <details>, where innerText is empty by design.
const raw = id => page.$eval('#' + id, e => e.textContent.replace(/\s+/g, ' ').trim());

async function setStudies(mode, text, level) {
  await page.click(`.mode[data-mode="${mode}"]`);
  await page.fill('#paste', text);
  if (level) await page.selectOption('#lev', String(level));
  await page.waitForTimeout(160);
}
const rowsOf = c => c.labels.map((L, i) =>
  c.mode === 'counts'
    ? `${L}, ${c.counts.et[i]}, ${c.counts.nt[i]}, ${c.counts.ec[i]}, ${c.counts.nc[i]}`
    : `${L}, ${c.yi[i]}, ${c.sei[i]}`).join('\n');

// Read the pooled rows out of the per-study table by data-col, not by index:
// the column order differs between the two modes.
async function poolRow(which) {
  return await page.evaluate(w => {
    const tr = [...document.querySelectorAll('#pertbl tr.pool')].find(r => r.cells[0].textContent.includes(w));
    if (!tr) return null;
    const g = c => tr.querySelector(`[data-col="${c}"]`).textContent.trim();
    return { est: g('est'), ci: g('ci') };
  }, which);
}
const parseCI = s => s.replace(/[[\]]/g, '').split(',').map(x => Number(x.trim()));

await page.goto(PAGE_URL, { waitUntil: 'load', timeout: 45000 });
await page.waitForTimeout(700);

// ---------- 1. default paint = es_low ----------
{
  const c = C('es_low');
  ok('default paint is not empty', (await txt('vhead')).length > 3);
  const fe = await poolRow('Fixed-effect'), re = await poolRow('Random-effects');
  near('default FE est', fe.est, c.fe.est, 3);
  near('default RE est', re.est, c.re.est, 3);
  near('default I2', Number((await txt('v3')).replace('%', '')), c.het.I2, 1);
  near('default tau2', await txt('v4'), c.het.tau2, 4);
}

// ---------- 2. every truth case, both modes, all levels ----------
for (const name of ['es_low', 'es_high', 'es_homog', 'es_k2', 'es_neg', 'es_k10', 'es_dominant',
                    'es_low_90', 'es_low_99', 'counts_basic', 'counts_zero', 'counts_high']) {
  const c = C(name);
  if (!c) { ok(`case ${name} exists in truth`, false); continue; }
  await setStudies(c.mode, rowsOf(c), c.level);
  const isOR = c.mode === 'counts';
  const tf = v => isOR ? Math.exp(v) : v;   // page shows counts pools as odds ratios

  const fe = await poolRow('Fixed-effect'), re = await poolRow('Random-effects');
  near(`${name} FE est`, fe.est, tf(c.fe.est), 3);
  near(`${name} RE est`, re.est, tf(c.re.est), 3);
  const feCI = parseCI(fe.ci), reCI = parseCI(re.ci);
  near(`${name} FE lo`, feCI[0], tf(c.fe.lo), 3);
  near(`${name} FE hi`, feCI[1], tf(c.fe.hi), 3);
  near(`${name} RE lo`, reCI[0], tf(c.re.lo), 3);
  near(`${name} RE hi`, reCI[1], tf(c.re.hi), 3);

  // heterogeneity block
  const h = await inner('hrows');
  near(`${name} I2 stat`, Number((await txt('v3')).replace('%', '')), c.het.I2, 1);
  near(`${name} tau2 stat`, await txt('v4'), c.het.tau2, 4);
  ok(`${name} Q shown`, h.includes('Q = ' + c.het.Q.toFixed(3)), h.split('\n')[0]);
  ok(`${name} df shown`, h.includes('df = ' + c.het.df));

  // per-study weights vs metafor's weights(res)
  const w = await page.evaluate(() => [...document.querySelectorAll('#pertbl tr')]
    .filter(r => !r.classList.contains('pool') && r.cells.length && r.cells[0].tagName === 'TD')
    .map(r => ({ fe: r.querySelector('[data-col="wfe"]').textContent.trim(),
                 re: r.querySelector('[data-col="wre"]').textContent.trim() })));
  ok(`${name} row count`, w.length === c.labels.length, w.length);
  for (let i = 0; i < c.labels.length; i++) {
    near(`${name} w${i + 1} FE%`, w[i].fe.replace('%', ''), c.fe.weights[i], 1);
    near(`${name} w${i + 1} RE%`, w[i].re.replace('%', ''), c.re.weights[i], 1);
  }
  // forest plot drew one square per study plus 2 diamonds
  const sq = await page.$$eval('#forest rect', n => n.length);
  const di = await page.$$eval('#forest polygon', n => n.length);
  ok(`${name} forest squares`, sq === c.labels.length, sq);
  ok(`${name} forest diamonds >= 2`, di >= 2, di);
}

