/*
  Gate for tools/lib/lmer-math.js against Scripts/tool-truth/lmer-output-interpreter.json
  (generated by real lme4 / performance runs in R 4.6.0).

  What is asserted:
   1. The parser recovers every variance component, every fixed-effect row, nobs and
      group counts from the REAL printed summaries, matching VarCorr()/coef(summary())
      to within the precision R actually printed.
   2. ICC from the exact variance components == performance::icc adjusted, machine
      precision, for every non-slope case (random intercept, crossed, glmer logit).
   3. For the random-slope case we assert the OPPOSITE: performance::icc is provably
      NOT recoverable from the paste, and our at-zero reading is what we claim it is.
   4. Wald CIs reproduce confint(method="Wald") bit-exactly.
   5. Malformed pastes produce a clear error and never throw.
*/
var fs = require('fs');
var path = require('path');
var T = require(path.join(__dirname, 'lmer-output-interpreter.json'));
var L = require(path.join(__dirname, '..', '..', 'tools', 'lib', 'lmer-math.js'));

var pass = 0, fail = 0, notes = [];
function ok(cond, label, detail) {
  if (cond) { pass++; } else { fail++; notes.push('FAIL: ' + label + (detail ? '  [' + detail + ']' : '')); }
}
function close(a, b, tol, label) {
  var d = Math.abs(a - b);
  var rel = Math.abs(b) > 1e-12 ? d / Math.abs(b) : d;
  ok(rel <= tol || d <= tol, label, 'got ' + a + ' want ' + b + ' rel ' + rel.toExponential(2));
  return rel;
}

/*
  Parsed values come out of TEXT R already rounded (default digits=7 gives e.g.
  "37.12" for 37.12382676676863). So the right assertion is not a hand-picked
  tolerance but the exact rounding contract: a correctly-parsed value must sit
  within half a unit of the last decimal place R actually printed. The bound is
  derived from the printed representation itself, so it cannot be fudged.
*/
function printedBound(x) {
  var s = String(x);
  var em = s.match(/^-?(\d*(?:\.(\d*))?)[eE]([-+]?\d+)$/);
  if (em) {
    var mdec = (em[2] || '').length;
    return 0.5 * Math.pow(10, -mdec) * Math.pow(10, parseInt(em[3], 10));
  }
  var dec = (s.split('.')[1] || '').length;
  return 0.5 * Math.pow(10, -dec);
}
// assert `got` (read from the printed text) is `want` (the exact R value) rounded
// to the precision the console printed.
function closePrinted(got, want, label) {
  if (got == null) { ok(false, label, 'got null'); return; }
  var bound = printedBound(got) * (1 + 1e-9) + 1e-12;
  var d = Math.abs(got - want);
  ok(d <= bound, label, 'printed ' + got + ' exact ' + want + ' diff ' + d.toExponential(2) + ' > half-ulp ' + bound.toExponential(2));
}

/* ---------------------------------------------------------------- 1. PARSER */
var PRESETS = ['ri', 'rs', 'glmer', 'lmertest'];
PRESETS.forEach(function (key) {
  var p = T.presets[key];
  var res = L.parse(p.summary_text);
  ok(res.ok, 'parse ' + key + ' succeeds', res.error);
  if (!res.ok) return;
  var m = res.model;

  // kind / family / link
  var wantKind = key === 'glmer' ? 'glmer' : 'lmer';
  ok(m.kind === wantKind, 'parse ' + key + ' kind=' + wantKind, m.kind);
  if (key === 'glmer') {
    ok(m.family === 'binomial', 'parse glmer family', m.family);
    ok(m.link === 'logit', 'parse glmer link', m.link);
  }
  if (key === 'lmertest') ok(m.isLmerTest === true, 'parse lmertest flag');

  // nobs + group counts
  ok(m.nobs === p.nobs, 'parse ' + key + ' nobs', m.nobs + ' vs ' + p.nobs);
  var gnames = Object.keys(p.ngrps);
  ok(m.groups.length === gnames.length, 'parse ' + key + ' n grouping factors');
  gnames.forEach(function (g) {
    var got = m.groups.filter(function (x) { return x.name === g; })[0];
    ok(got && got.n === p.ngrps[g], 'parse ' + key + ' groups ' + g, got ? got.n : 'missing');
  });

  // variance components vs VarCorr, to the precision R printed (default digits=7)
  var vcRand = p.varcorr.filter(function (v) { return v.grp !== 'Residual' && !v.var2; });
  var flat = [];
  m.random.groups.forEach(function (g) {
    g.terms.forEach(function (t) { flat.push({ grp: g.name, name: t.name, variance: t.variance, sd: t.sd }); });
  });
  ok(flat.length === vcRand.length, 'parse ' + key + ' random term count', flat.length + ' vs ' + vcRand.length);
  vcRand.forEach(function (v) {
    var got = flat.filter(function (f) { return f.grp === v.grp && f.name === v.var1; })[0];
    ok(!!got, 'parse ' + key + ' term ' + v.grp + '/' + v.var1);
    if (got) {
      // printed with ~5 significant digits -> relative tolerance 1e-4
      closePrinted(got.variance, v.vcov, 'parse ' + key + ' var ' + v.grp + '/' + v.var1);
      closePrinted(got.sd, v.sdcor, 'parse ' + key + ' sd ' + v.grp + '/' + v.var1);
    }
  });
  var vcRes = p.varcorr.filter(function (v) { return v.grp === 'Residual'; })[0];
  if (vcRes) {
    ok(!!m.random.residual, 'parse ' + key + ' has residual row');
    if (m.random.residual) closePrinted(m.random.residual.variance, vcRes.vcov, 'parse ' + key + ' residual var');
  } else {
    ok(m.random.residual === null, 'parse ' + key + ' correctly has NO residual row (glmer)');
  }

  // fixed effects vs coef(summary(m))
  ok(m.fixed.rows.length === p.fixed.length, 'parse ' + key + ' fixed row count', m.fixed.rows.length + ' vs ' + p.fixed.length);
  p.fixed.forEach(function (f) {
    var got = m.fixed.rows.filter(function (r) { return r.term === f.term; })[0];
    ok(!!got, 'parse ' + key + ' fixed term ' + f.term);
    if (!got) return;
    closePrinted(got.estimate, f.Estimate, 'parse ' + key + ' est ' + f.term);
    closePrinted(got.se, f['Std. Error'], 'parse ' + key + ' se ' + f.term);
    var stat = f['t value'] != null ? f['t value'] : f['z value'];
    if (stat != null) closePrinted(got.stat, stat, 'parse ' + key + ' stat ' + f.term);
    if (f['df'] != null) closePrinted(got.df, f['df'], 'parse ' + key + ' df ' + f.term);
  });

  // p-value column presence must match the model type
  var wantP = (key === 'glmer' || key === 'lmertest');
  ok(m.fixed.hasP === wantP, 'parse ' + key + ' hasP=' + wantP, String(m.fixed.hasP));
  var wantStat = key === 'glmer' ? 'z' : 't';
  ok(m.fixed.statName === wantStat, 'parse ' + key + ' statName=' + wantStat, m.fixed.statName);
  ok(m.fixed.hasDf === (key === 'lmertest'), 'parse ' + key + ' hasDf', String(m.fixed.hasDf));

  // regions: every summary must be fully labelled for the anatomy view
  var need = ['header', 'formula', 'random', 'obs', 'fixed'];
  need.forEach(function (r) {
    ok(m.regions.some(function (x) { return x.key === r; }), 'parse ' + key + ' region ' + r);
  });
});

// bounded p-values ("< 2e-16") must survive as bounded, not as NaN
(function () {
  var m = L.parse(T.presets.glmer.summary_text).model;
  var shout = m.fixed.rows.filter(function (r) { return r.term === 'btypeshout'; })[0];
  ok(shout && shout.pBounded === true, 'glmer bounded p flagged');
  ok(shout && shout.p === 2e-16, 'glmer bounded p value', shout && shout.p);
  var anger = m.fixed.rows.filter(function (r) { return r.term === 'Anger'; })[0];
  ok(anger && Math.abs(anger.p - 0.000636) < 1e-9, 'glmer plain p parsed', anger && anger.p);
  ok(anger && anger.stars === '***', 'glmer stars parsed', anger && anger.stars);
})();

/* ------------------------------------------------------------------ 2. ICC */
// Build a synthetic model object straight from the EXACT VarCorr numbers so the
// ICC arithmetic is tested without print-rounding in the way.
function modelFromCase(c) {
  var groups = {};
  var order = [];
  c.varcorr.filter(function (v) { return v.grp !== 'Residual' && !v.var2; }).forEach(function (v) {
    if (!groups[v.grp]) { groups[v.grp] = { name: v.grp, terms: [] }; order.push(v.grp); }
    groups[v.grp].terms.push({ name: v.var1, variance: v.vcov, sd: v.sdcor, corr: [] });
  });
  var res = c.varcorr.filter(function (v) { return v.grp === 'Residual'; })[0];
  return {
    kind: c.kind === 'glmer' ? 'glmer' : 'lmer',
    link: c.kind === 'glmer' ? 'logit' : null,
    family: c.kind === 'glmer' ? 'binomial' : null,
    random: {
      groups: order.map(function (g) { return groups[g]; }),
      residual: res ? { variance: res.vcov, sd: res.sdcor } : null
    },
    nobs: c.nobs, groups: [{ name: order[0], n: c.ngrps }]
  };
}

var worst = 0, slopeSeen = 0;
T.cases.forEach(function (c) {
  var m = modelFromCase(c);
  var r = L.icc(m);
  ok(r.ok, 'icc computed ' + c.id, r.reason);
  if (!r.ok) return;
  var hasSlope = c.varcorr.some(function (v) { return v.grp !== 'Residual' && v.var2; });
  if (hasSlope) {
    slopeSeen++;
    // The claim under test is a NEGATIVE one: performance::icc must NOT be
    // reproducible from the components alone, and we must be flagging that.
    ok(r.atZeroOnly === true, 'icc flags at-zero-only for slope case ' + c.id);
    ok(Math.abs(r.value - c.icc_adjusted) > 1e-3,
      'icc slope case ' + c.id + ' provably differs from performance::icc (that is the point)',
      'ours ' + r.value + ' perf ' + c.icc_adjusted);
    // and our at-zero value must be exactly the intercept-variance reading
    var vi = c.varcorr[0].vcov, vr = c.varcorr.filter(function (v) { return v.grp === 'Residual'; })[0].vcov;
    close(r.value, vi / (vi + vr), 1e-15, 'icc at-zero identity ' + c.id);
  } else {
    ok(r.atZeroOnly === false, 'icc not flagged at-zero for ' + c.id);
    var rel = close(r.value, c.icc_adjusted, 1e-12, 'icc == performance::icc ' + c.id);
    if (rel > worst) worst = rel;
    if (c.kind === 'glmer') ok(r.latent === true && Math.abs(r.residual - T.pi2_3) < 1e-15, 'icc glmer uses pi^2/3 ' + c.id);
  }
});
ok(slopeSeen > 0, 'at least one random-slope case exercised');

/* --------------------------------------- 3. random-slope proof from R holds */
(function () {
  var p = T.rs_proof;
  var nak = p.v_int + 2 * p.mean_x * p.cov_int_slope + p.mean_x2 * p.v_slope;
  close(nak, p.nakagawa_var_random, 1e-12, 'Nakagawa var.random reproduced');
  close(nak / (nak + p.v_resid), p.performance_adjusted, 1e-12, 'Nakagawa ICC == performance::icc');
  // the whole honesty argument: the inputs mean_x / mean_x2 are DATA, and the
  // at-zero reading (all a paste can give) is materially different.
  ok(Math.abs(p.icc_at_x0 - p.performance_adjusted) > 0.2, 'at-zero ICC differs materially from performance::icc',
    p.icc_at_x0 + ' vs ' + p.performance_adjusted);
  ok(Math.abs(p.naive_sum_icc - p.performance_adjusted) > 0.2, 'naive summed ICC differs materially too',
    p.naive_sum_icc + ' vs ' + p.performance_adjusted);
})();

/* ------------------------------------------------------- 4. Wald intervals */
['ri', 'rs', 'glmer'].forEach(function (key) {
  var fx = T.presets[key].fixed;
  T.wald_ci[key].forEach(function (c) {
    var f = fx.filter(function (x) { return x.term === c.term; })[0];
    if (!f) return;
    var w = L.waldCI(f.Estimate, f['Std. Error'], 0.95);
    close(w.lower, c.lower, 1e-12, 'wald lower ' + key + '/' + c.term);
    close(w.upper, c.upper, 1e-12, 'wald upper ' + key + '/' + c.term);
  });
});

