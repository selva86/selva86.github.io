/* ------------------------------------------------ 6. paste-precision budget */
// ICC computed from the ROUNDED text must still land within print-rounding of the
// exact performance::icc value. This is the claim the page is allowed to make.
PRESETS.forEach(function (key) {
  if (key === 'rs') return; // slope case is at-zero by design, checked above
  var res = L.parse(T.presets[key].summary_text);
  var r = L.icc(res.model);
  ok(r.ok, 'paste-ICC ' + key);
  if (!r.ok) return;
  var d = Math.abs(r.value - T.presets[key].icc_adjusted);
  ok(d < 5e-5, 'paste-ICC ' + key + ' within print-rounding of performance::icc',
    'diff ' + d.toExponential(2));
  notes.push('  note: ' + key + ' ICC from paste = ' + r.value.toFixed(6) +
    ', exact = ' + T.presets[key].icc_adjusted.toFixed(6) + ', diff = ' + d.toExponential(2));
});

/* -------------------------------------------------------- 7. design effect */
(function () {
  var res = L.parse(T.presets.ri.summary_text);
  var r = L.icc(res.model);
  var de = L.designEffect(res.model, r.value);
  ok(de !== null, 'design effect computed');
  ok(Math.abs(de.avgClusterSize - 10) < 1e-12, 'sleepstudy avg cluster size = 10', de && de.avgClusterSize);
  var want = 1 + (10 - 1) * r.value;
  close(de.de, want, 1e-15, 'design effect = 1+(m-1)*ICC');
  close(de.neff, 180 / want, 1e-15, 'effective n = nobs/DE');
  notes.push('  note: sleepstudy DE = ' + de.de.toFixed(3) + ', n_eff = ' + de.neff.toFixed(1) + ' (of 180 rows)');
})();

console.log(notes.join('\n'));
console.log('\nworst non-slope ICC rel error: ' + worst.toExponential(2));
console.log('PASS ' + pass + '  FAIL ' + fail);
process.exit(fail ? 1 : 0);
