  { input: '   \n  \n', label: 'whitespace only' },
  { input: 'hello world', label: 'junk text' },
  { input: '{"a":1}', label: 'json' },
  { input: 'Linear mixed model fit by REML [\'lmerMod\']\nFormula: y ~ x + (1|g)', label: 'header only, no blocks' },
  { input: T.presets.ri.summary_text.split('\n').slice(0, 8).join('\n'), label: 'truncated paste' },
  { input: 'Call:\nlm(formula = y ~ x)\n\nCoefficients:\n            Estimate Std. Error t value Pr(>|t|)\n(Intercept)   1.0000     0.1000   10.00   <2e-16\n\nResidual standard error: 1 on 98 degrees of freedom', label: 'lm() output' },
  { input: 'Call:\nglm(formula = y ~ x, family = binomial)\n\nCoefficients:\n            Estimate Std. Error z value Pr(>|z|)\n(Intercept)   1.0000     0.1000   10.00   <2e-16\n\n(Dispersion parameter for binomial family taken to be 1)', label: 'glm() output' }
