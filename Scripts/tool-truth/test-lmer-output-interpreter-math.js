BAD.forEach(function (b) {
  var r;
  try { r = L.parse(b.input); } catch (e) { ok(false, 'malformed "' + b.label + '" must not throw', e.message); return; }
  ok(r && r.ok === false, 'malformed "' + b.label + '" rejected');
  ok(r && typeof r.error === 'string' && r.error.length > 25, 'malformed "' + b.label + '" has a helpful message', r && r.error);
  ok(r && !/undefined|NaN|\[object/.test(r.error), 'malformed "' + b.label + '" message is clean', r && r.error);
});
// the lm/glm mispastes should be routed to the right sibling tool
ok(L.parse(BAD[6].input).hint === 'lm', 'lm mispaste hints at lm tool');
ok(L.parse(BAD[7].input).hint === 'glm', 'glm mispaste hints at glm tool');

