/* Pull the R code the tool actually emits, straight out of the live page, so it can
   be run for real by verify-bayes-emitted-r.R. Emitting R that does not run is a way
   of lying to the reader that no unit test would catch.

   Only the rstanarm presets are extracted: brms needs a C++ toolchain that this box
   does not have, so its emitted code cannot be executed here and is not claimed to be.

   Usage: node Scripts/tool-truth/extract-bayes-emitted-r.js [baseURL]
   Out:   Scripts/tool-truth/bayes-emitted-r.json */
'use strict';
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const truth = require('./bayesian-output-interpreter.json');

const BASE = process.argv[2] || 'http://localhost:8917';
const URL = BASE + '/tools/bayesian-output-interpreter.html';
const OUT = path.join(__dirname, 'bayes-emitted-r.json');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto(URL, { waitUntil: 'networkidle' });

  const out = {};
  for (const key of Object.keys(truth.presets)) {
    await page.click(`.chip[data-scen="${key}"]`);
    await page.waitForTimeout(60);
    const code = await page.$eval('#rcodepre', e => e.textContent);
    if (!code || code.length < 40) throw new Error('no R emitted for preset ' + key);
    out[key] = code;
  }
  await browser.close();

  fs.writeFileSync(OUT, JSON.stringify({
    note: 'GENERATED by extract-bayes-emitted-r.js. The exact text of the tool\'s ' +
          '"same reading, from the fit object in R" block for each rstanarm preset. ' +
          'verify-bayes-emitted-r.R runs every line of it.',
    emitted: out
  }, null, 2) + '\n');
  console.log('wrote ' + OUT + ' (' + Object.keys(out).length + ' presets)');
})().catch(e => { console.error(e); process.exit(1); });
